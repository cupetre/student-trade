// Field errors are kept as keys (so they follow the language switch) or as
// { text } when the message came from the server.
export function errorText(t, err) {
    if (!err) return '';
    if (typeof err === 'object') return err.text;
    const value = t.errors[err] ?? t.landlord[err];
    return typeof value === 'function' ? value(MIN_PASSWORD_LENGTH) : value;
}
