// Slovenian counts in four forms: 1 predmet, 2 predmeta, 3-4 predmeti, 5+ predmetov
// (decided by the last two digits: 101 predmet, 102 predmeta ...)
function plural(n, one, two, few, many) {
    const mod = Math.abs(Number(n)) % 100;
    if (mod === 1) return one;
    if (mod === 2) return two;
    if (mod === 3 || mod === 4) return few;
    return many;
}

